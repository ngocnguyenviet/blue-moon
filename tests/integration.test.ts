async function balanced(householdId:string){
  const report=await reports.report({householdId});
  for(const row of report.rows)expect(row.assessment).toBe(row.allocated+row.writtenOff+row.outstanding);
  expect(report.summary.credit).toBeGreaterThanOrEqual(0);
  return report;
}
